export const SEO_REGIONS = PLACE_NAMES.map((place) => ({
  city: SEO_CITY,
  place,
  label: place === SEO_CITY ? SEO_CITY : `${SEO_CITY} ${place}`,
}));

export function findSeoRegion(city, place) {
  if (city !== SEO_CITY) return null;
  if (!place) {
    return SEO_REGIONS.find((row) => row.place === SEO_CITY) || { city: SEO_CITY, place: SEO_CITY, label: SEO_CITY };
  }
  return SEO_REGIONS.find((row) => row.place === place) || null;
}

export function seoRegionPath(keywordSlug, region) {
  if (!region || region.place === SEO_CITY) {
    return `/${keywordSlug}/${encodeURIComponent(SEO_CITY)}`;
  }
  return `/${keywordSlug}/${encodeURIComponent(SEO_CITY)}/${encodeURIComponent(region.place)}`;
}
